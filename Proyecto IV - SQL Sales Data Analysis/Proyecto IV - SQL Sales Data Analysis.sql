--RELACIÓN ENTRE FACT_SALES Y DIM_PRODUCT
SELECT COUNT(*) AS Coincidencias
FROM FACT_SALES AS f
INNER JOIN DIM_PRODUCT AS p
    ON f.ITEM_CODE = p.ITEM;
GO

--VENTAS POR CATEGORÍA (ATTR3)

SELECT 
    p.ATTR3 AS Categoria,
    SUM(f.TOTAL_UNIT_SALES) AS Unidades_Vendidas,
    SUM(f.TOTAL_VALUE_SALES) AS Ventas_Totales
FROM FACT_SALES AS f
INNER JOIN DIM_PRODUCT AS p
    ON f.ITEM_CODE = p.ITEM
WHERE p.ATTR3 IS NOT NULL
GROUP BY p.ATTR3
ORDER BY Ventas_Totales DESC;
GO

-- VENTAS POR MARCA

SELECT 
    p.BRAND AS Marca,
    SUM(f.TOTAL_UNIT_SALES) AS Unidades_Vendidas,
    SUM(f.TOTAL_VALUE_SALES) AS Ventas_Totales
FROM FACT_SALES AS f
INNER JOIN DIM_PRODUCT AS p
    ON f.ITEM_CODE = p.ITEM
WHERE p.BRAND IS NOT NULL
GROUP BY p.BRAND
ORDER BY Ventas_Totales DESC;
GO

--VENTAS POR REGIÓN

SELECT
    REGION,
    SUM(TOTAL_UNIT_SALES) AS Unidades_Vendidas,
    SUM(TOTAL_VALUE_SALES) AS Ventas_Totales
FROM FACT_SALES
GROUP BY REGION
ORDER BY Ventas_Totales DESC;

--VENTAS POR PERÍODO
SELECT
    c.YEAR,
    c.MONTH,
    SUM(f.TOTAL_UNIT_SALES) AS Unidades_Vendidas,
    SUM(f.TOTAL_VALUE_SALES) AS Ventas_Totales
FROM FACT_SALES AS f
INNER JOIN DIM_CALENDAR AS c
    ON f.WEEK = c.WEEK
GROUP BY c.YEAR, c.MONTH
ORDER BY c.YEAR, c.MONTH;



