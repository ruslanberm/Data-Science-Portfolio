--Definir la estructura de las tablas necesarias para los conjuntos de datos (DIM_CATEGORY, DIM_PRODUCT, DIM_SEGMENT, DIM_CALENDAR, FACT_SALES).

CREATE TABLE DIM_CATEGORY (
    ID_CATEGORY INT PRIMARY KEY,
    CATEGORY VARCHAR(100)
);
GO


CREATE TABLE DIM_PRODUCT (
    MANUFACTURER VARCHAR(100),
    BRAND VARCHAR(100),
    ITEM VARCHAR(100),
    ITEM_DESCRIPTION VARCHAR(255),
    CATEGORY INT,
    FORMAT VARCHAR(100),
    ATTR1 VARCHAR(100),
    ATTR2 VARCHAR(100),
    ATTR3 VARCHAR(100)
);
GO


CREATE TABLE DIM_SEGMENT (
    CATEGORY INT,
    ATTR1 VARCHAR(100),
    ATTR2 VARCHAR(100),
    ATTR3 VARCHAR(100),
    FORMAT VARCHAR(100),
    SEGMENT VARCHAR(100)
);
GO


CREATE TABLE DIM_CALENDAR (
    WEEK VARCHAR(20) PRIMARY KEY,
    YEAR INT,
    MONTH INT,
    WEEK_NUMBER INT,
    DATE DATE
);
GO


CREATE TABLE FACT_SALES (
    WEEK VARCHAR(20),
    ITEM_CODE VARCHAR(100),
    TOTAL_UNIT_SALES DECIMAL(18,3),
    TOTAL_VALUE_SALES DECIMAL(18,3),
    TOTAL_UNIT_AVG_WEEKLY_SALES DECIMAL(18,3),
    REGION VARCHAR(100)
);
GO


